ALTER TABLE demo_usos
    ADD COLUMN IF NOT EXISTS ultima_actividad DATETIME DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS segundos_activos INT UNSIGNED NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS facilidad TINYINT UNSIGNED DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS instalaria VARCHAR(10) DEFAULT NULL;

CREATE TABLE IF NOT EXISTS demo_eventos (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    uso_id BIGINT UNSIGNED NOT NULL,
    fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    seccion VARCHAR(30) NOT NULL,
    accion VARCHAR(40) NOT NULL,
    resultado VARCHAR(15) NOT NULL,
    INDEX demo_eventos_uso (uso_id, id),
    CONSTRAINT demo_eventos_visita FOREIGN KEY (uso_id) REFERENCES demo_usos(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS contacto_mensajes (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL DEFAULT '',
    email VARCHAR(254) NOT NULL,
    tema VARCHAR(30) NOT NULL,
    mensaje TEXT NOT NULL,
    fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    leido TINYINT NOT NULL DEFAULT 0,
    INDEX contacto_fecha (fecha)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
